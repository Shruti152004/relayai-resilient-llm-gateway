"""Pydantic Data Transfer Objects (DTOs) for Strict API Contracts.

Strictly defines schemas for GET /health, POST /chat, and GET /sessions/{id}/messages
as mandated by the RelayAI assignment specification.
"""

from typing import Any, List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator


# ==============================================================================
# Health Contract
# ==============================================================================
class HealthResponse(BaseModel):
    """Schema for GET /health response."""

    status: str = Field(default="ok", description="Server health status.")
    keys_configured: int = Field(..., description="Number of API keys loaded in pool.")
    cache_enabled: bool = Field(default=True, description="Whether response caching is enabled.")


# ==============================================================================
# Chat Contracts (POST /chat)
# ==============================================================================
class ChatRequest(BaseModel):
    """Schema for POST /chat request payload."""

    session_id: str = Field(
        ...,
        min_length=1,
        max_length=128,
        description="Unique session identifier generated by the client.",
    )
    message: str = Field(
        ...,
        description="User message content, 1-4000 characters after whitespace trimming.",
    )
    system_prompt: Optional[str] = Field(
        default=None,
        description="Optional system prompt to override default persona for this session.",
    )

    @field_validator("message")
    @classmethod
    def validate_message(cls, v: str) -> str:
        trimmed = v.strip()
        if not trimmed:
            raise ValueError("Message cannot be empty or whitespace only.")
        if len(trimmed) > 4000:
            raise ValueError("Message exceeds 4000 character maximum limit.")
        return trimmed

    @field_validator("session_id")
    @classmethod
    def validate_session_id(cls, v: str) -> str:
        trimmed = v.strip()
        if not trimmed:
            raise ValueError("session_id cannot be empty.")
        if len(trimmed) > 128:
            raise ValueError("session_id cannot exceed 128 characters.")
        return trimmed


class ChatMetadata(BaseModel):
    """Per-request metadata contract returned with assistant replies."""

    resolution_source: str = Field(
        ...,
        description="Source of response: strictly 'LIVE_INFERENCE' or 'LLM_CACHE'.",
    )
    model: str = Field(..., description="LiteLLM model name that generated or cached the reply.")
    latency_ms: int = Field(
        ...,
        description="Server-measured wall-clock execution time in milliseconds.",
    )
    input_tokens: int = Field(
        ...,
        description="Prompt tokens for this specific request only (system + history + current message).",
    )
    output_tokens: int = Field(
        ...,
        description="Completion tokens produced in this specific reply.",
    )
    key_id: Optional[str] = Field(
        default=None,
        description="Alias of the key that answered ('key_1', 'key_2'). Strictly null on LLM_CACHE.",
    )
    fallback_attempts: int = Field(
        default=0,
        description="Count of keys that failed before this succeeded. Strictly 0 on LLM_CACHE.",
    )


class ChatResponse(BaseModel):
    """Schema for POST /chat 200 OK response."""

    session_id: str = Field(..., description="Echoed session identifier.")
    reply: str = Field(..., min_length=1, description="Assistant response text.")
    metadata: ChatMetadata = Field(..., description="Request execution metadata.")


# ==============================================================================
# Session Message History Contracts (GET /sessions/{session_id}/messages)
# ==============================================================================
class AssistantMetadataSummary(BaseModel):
    """Metadata included for assistant messages in session history."""

    model_config = ConfigDict(extra="allow")

    resolution_source: str
    input_tokens: int
    output_tokens: int


class MessageItem(BaseModel):
    """Single message item stored in SQLite history."""

    role: str = Field(..., description="'user' or 'assistant'.")
    content: str = Field(..., description="Message text.")
    metadata: Optional[AssistantMetadataSummary] = Field(
        default=None,
        description="Assistant metadata only. Omitted on user messages.",
    )


class SessionMessagesResponse(BaseModel):
    """Schema for GET /sessions/{session_id}/messages 200 OK response."""

    session_id: str = Field(..., description="Target session identifier.")
    messages: List[MessageItem] = Field(
        default_factory=list,
        description="Chronological message history without system prompt.",
    )


# ==============================================================================
# Standard Error Contract
# ==============================================================================
class DetailError(BaseModel):
    """Standard JSON error format with detail field."""

    detail: Any = Field(..., description="Human-readable explanation of error.")

